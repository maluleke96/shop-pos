/**
 * Netlify build step: write src/js/env.js from environment variables.
 * Never embeds the service role key or database password.
 */
const fs = require('fs');
const path = require('path');

const url = process.env.SHOP_POS_SUPABASE_URL || process.env.SUPABASE_URL || '';
const anon = process.env.SHOP_POS_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY || '';
const rpc = process.env.SHOP_POS_RPC_URL || process.env.RPC_URL || '';

const out = path.join(__dirname, '..', 'src', 'js', 'env.js');
const body = `/* Generated by scripts/netlify-build-env.js — do not edit */
window.__SHOP_POS_ENV__ = {
  SUPABASE_URL: ${JSON.stringify(url)},
  SUPABASE_ANON_KEY: ${JSON.stringify(anon)},
  SHOP_POS_SUPABASE_URL: ${JSON.stringify(url)},
  SHOP_POS_SUPABASE_ANON_KEY: ${JSON.stringify(anon)},
  RPC_URL: ${JSON.stringify(rpc)},
  SHOP_POS_RPC_URL: ${JSON.stringify(rpc)}
};
window.__SHOP_POS_USE_SUPABASE__ = ${url && anon ? 'true' : 'false'};
`;

fs.writeFileSync(out, body);
console.log(
  'Wrote',
  out,
  url ? '(Supabase URL set)' : '(Supabase URL MISSING)',
  rpc ? `(RPC ${rpc})` : '(RPC same-origin /rpc)'
);
